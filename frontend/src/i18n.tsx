/**
 * Both tables, so a test can prove they hold the same keys. A key present in only one language
 * does not fail anywhere at runtime -- {@link t} quietly falls back to Chinese -- which is exactly
 * why it is worth a test rather than a code review.
 */
export const dictionaries: Record<Lang, Record<string, string>> = { zh, en };

export function parseLang(raw?: string | null): Lang {
  if (!raw) return "zh";
  const value = raw.trim().toLowerCase();
  if (value === "en" || value.startsWith("en-") || value === "english") return "en";
  return "zh";
}

export function t(lang: Lang, key: string, vars?: Vars): string {
  const table = lang === "en" ? en : zh;
  let text = table[key] ?? zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function groupLabel(lang: Lang, group: string): string {
  const key = GROUP_ID[group];
  return key ? t(lang, key) : group;
}

export function fieldLabel(lang: Lang, field: { key: string; label: string }): string {
  return lang === "en" && SETTINGS_EN[field.key] ? SETTINGS_EN[field.key].label : field.label;
}

export function fieldHint(lang: Lang, field: { key: string; hint: string }): string {
  return lang === "en" && SETTINGS_EN[field.key] ? SETTINGS_EN[field.key].hint : field.hint;
}

export function expressionLabel(lang: Lang, expression: string | null | undefined): string {
  if (!expression) return "";
  const key = EXPR_I18N[expression];
  return key ? t(lang, key) : expression;
}

export function approachLabel(lang: Lang, approach: string | null | undefined): string {
  const key = APPROACH_I18N[approach ?? "action"];
  return key ? t(lang, key) : (approach ?? "");
}

export function statLabel(lang: Lang, stat: string): string {
  const entry = STAT_I18N[stat];
  return entry ? t(lang, entry.label) : stat;
}

const LocaleContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: "zh",
  setLang: () => {},
});

export function LocaleProvider({ lang, onChange, children }: { lang: Lang; onChange: (lang: Lang) => void; children: ReactNode }) {
  useEffect(() => {
    const root = typeof document !== "undefined" ? document.documentElement : null;
    if (root) root.lang = lang === "en" ? "en" : "zh-CN";
  }, [lang]);
  return <LocaleContext.Provider value={{ lang, setLang: onChange }}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}

export function useT() {
  const { lang } = useLocale();
  return useCallback((key: string, vars?: Vars) => t(lang, key, vars), [lang]);
}

export function LanguageSwitcher() {
  const { lang, setLang } = useLocale();
  return (
    <div className="language-switch" role="group" aria-label={t(lang, "language")}>
      <button type="button" className={lang === "zh" ? "on" : ""} aria-pressed={lang === "zh"} onClick={() => setLang("zh")}>中文</button>
      <button type="button" className={lang === "en" ? "on" : ""} aria-pressed={lang === "en"} onClick={() => setLang("en")}>English</button>
    </div>
  );
}

